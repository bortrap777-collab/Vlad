import { PixelCanvas } from './art/raster';
import * as E from './art/environment';
import { drawCharacter } from './art/characters';
import { CAST } from './art/cast';
const out = process.argv[2];
const camX = Number(process.argv[3] ?? 380);
const sky = E.drawSky(), far = E.drawFarCity(), mid = E.drawMidCity(), yard = E.drawCourtyard();
const c = new PixelCanvas(480, 270);
c.blit(sky, 0, 0);
c.blit(far, -Math.round(camX * 0.15), 0);
c.blit(mid, -Math.round(camX * 0.45), 0);
c.blit(yard, -camX, 0);
const place = (p: PixelCanvas, x: number, yBottom: number, flip=false) => c.blit(p, Math.round(x - camX - p.w / 2), yBottom - p.h, flip);
place(E.drawSlide(), 520, 214);
place(E.drawSwings(), 700, 214);
for (const sx of [660, 740]) place(E.drawSwingSeat(), sx, 214 - 32);
place(E.drawClimber(), 900, 210);
place(E.drawBench(), 300, 226);
place(E.drawLamp(), 560, 232);
place(E.drawCar(), 1060, 228);
const kolya = CAST[0], olya = CAST[1];
place(E.drawShadow(20), camX + 230, 240);
place(drawCharacter(kolya), camX + 230, 241);
place(E.drawShadow(20), camX + 268, 240);
place(drawCharacter(olya), camX + 268, 241, true);
c.scaled(2).savePNG(out);
