/** End-of-chapter recap lines, chosen from the player's recorded choices and flags. */
import type { GameState } from '../core/state';

export function chapterSummary(s: GameState): string[] {
  const c = (t: string) => s.choices.includes(t);
  const f = s.flags;
  const out: string[] = [];
  out.push(c('intro_honest') ? 'Ты прямо спросил родителей, почему они ругаются.' : c('intro_cheeky') ? 'Ты сделал вид, что тебе всё равно. Мама расстроилась.' : 'Ты молча ушёл гулять, чтобы не слушать ссору.');
  out.push(f.dog_fed ? 'Ты поделился с бездомным псом горбушкой — и он тебе поверил.' : 'Ты долго уговаривал испуганного пса — и он тебе поверил.');
  if (f.dog_named) out.push('У пса теперь есть имя — Рыжий.');
  if (f.cans_thrown) out.push('Банки, которые мучили собаку, отправились в мусорный бак.');
  out.push(c('bully_cheeky') ? 'Ты огрызнулся на хулиганов — и разозлил Толстого ещё сильнее.' : c('bully_diplomat') ? 'Ты пытался решить дело миром, но пришлось постоять за себя.' : 'Ты твёрдо заступился за Олю.');
  if (f.dog_helped) out.push('В драке Рыжий пришёл тебе на помощь.');
  out.push(f.seryoga_cheeky ? 'Серёга запомнил тебя как дерзкого новенького.' : 'Серёга, кажется, тебя зауважал.');
  out.push(Number(f.olya_trust) >= 2 ? 'Оля тебе доверяет.' : 'Оля только начинает тебе доверять.');
  if (s.clues.includes('insight_garages')) out.push('Ты понял, что Димка был у гаражей в ту самую ночь.');
  if (f.gave_mitten) out.push('Ты отдал Димкину варежку участковому. Правильно ли это было?');
  else if (f.hid_mitten) out.push('Ты не показал варежку участковому. Она всё ещё у тебя.');
  else if (f.asked_officer) out.push('Ты спросил участкового напрямую. Он не ответил — по-настоящему.');
  out.push(c('promise') ? 'Ты пообещал маме не лазить по гаражам…' : 'Ты не стал давать маме обещание, которое не сможешь сдержать.');
  return out;
}

