/**
 * All Chapter 1 dialogue. Russian player-facing text only lives in src/content.
 * Node ids are local to each dialogue; `next: null` ends the conversation.
 */
import type { CharId, Choice, Dialogue, DialogueNode, Effect, Expr } from '../core/types';

function n(speaker: CharId, expr: Expr, text: string, next: string | null, extra: Partial<DialogueNode> = {}): DialogueNode {
  return { speaker, expr, text, next, ...extra };
}
function ch(text: string, next: string | null, extra: Partial<Choice> = {}): Choice {
  return { text, next, ...extra };
}
const fx = (...e: Effect[]) => ({ effects: e });

/** Short single-node inspection monologues. */
function inspect(id: string, text: string, effects: Effect[] = [], speaker: CharId = 'kolya', expr: Expr = 'neutral'): Dialogue {
  return { id, start: [{ node: 'a' }], nodes: { a: n(speaker, expr, text, null, { effects }) } };
}

export const DIALOGUES: Record<string, Dialogue> = {};
function add(d: Dialogue) {
  DIALOGUES[d.id] = d;
}

